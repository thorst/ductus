/** True when `segment`-`field` should be accessed as a Field (components), false for a plain string. */
export function isComposite(segment: string, field: number): boolean {
  const def = SEGMENTS[segment];
  if (!def) return true; // unknown and Z-segments: generic Field access
  const entry = def[field - 1];
  if (!entry) return true;
  return entry[1] === "varies" || entry[1] in DATATYPES;
}
